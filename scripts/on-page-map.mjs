#!/usr/bin/env node
/**
 * Generates docs/seo/on-page-map.md from a running server, so the on-page
 * map always reflects what is actually rendered.
 * Usage: node scripts/on-page-map.mjs http://localhost:3000
 */
import { writeFileSync } from "node:fs";

const base = (process.argv[2] ?? "http://localhost:3000").replace(/\/$/, "");
const origin = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://ampleassociates.com").replace(/\/$/, "");
const decode = (s = "") =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&rsquo;/g, "’");
const strip = (s = "") =>
  decode(s.replace(/<[^>]+>/g, ""))
    .replace(/\s+/g, " ")
    .trim();
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");

const sitemap = await (await fetch(`${base}/sitemap.xml`)).text();
const paths = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].replace(origin, ""));

const rows = [];
for (const path of paths) {
  const html = await (await fetch(base + path)).text();
  const title = decode(html.match(/<title>([^<]*)<\/title>/)?.[1]);
  const desc = decode(html.match(/<meta name="description" content="([^"]*)"/)?.[1]);
  const h1 = strip(html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1]);
  const h2s = [...html.matchAll(/<h2[^>]*>([\s\S]*?)<\/h2>/g)].map((m) => strip(m[1])).filter(Boolean);
  const schema = [...html.matchAll(/"@type":"([A-Za-z]+)"/g)].map((m) => m[1]);
  const topTypes = [...new Set(schema.filter((t) => !["ListItem", "Question", "Answer", "Country"].includes(t)))];
  rows.push({ path, title, desc, h1, h2: h2s.slice(0, 6).join(" · "), schema: topTypes.join(", ") });
}

const out = `# On-Page SEO Map

Generated by \`scripts/on-page-map.mjs\` from the rendered site on ${new Date().toISOString().slice(0, 10)}. Re-run after content changes.

Every indexable page has a unique title and description, a self-referencing canonical, Open Graph and Twitter tags, exactly one H1 and breadcrumbs (interior pages). Structured data is listed per page.

| URL | Title (chars) | Meta description (chars) | H1 | Key H2s | Structured data |
|---|---|---|---|---|---|
${rows
  .map(
    (r) =>
      `| \`${r.path}\` | ${cell(r.title)} (${r.title.length}) | ${cell(r.desc)} (${r.desc.length}) | ${cell(r.h1)} | ${cell(r.h2)} | ${cell(r.schema)} |`,
  )
  .join("\n")}
`;
writeFileSync("docs/seo/on-page-map.md", out);
console.log(`Wrote docs/seo/on-page-map.md (${rows.length} pages)`);
