// Generates the homepage hero map: a dotted equirectangular map of the
// UK-to-Nepal corridor, plus snapped pin positions for London and Nepal.
// Run once when the region or cities change:  node scripts/generate-hero-map.mjs
// Outputs public/maps/{wide,corridor}{,-light}.svg and src/content/hero-map.ts (all committed).
import { mkdirSync, writeFileSync } from "node:fs";
import DottedMap from "dotted-map";

// "wide" sits behind the desktop hero: the Atlantic on the left leaves room for
// the headline. "corridor" is the tighter UK-to-Nepal crop used below the text
// on smaller screens.
const variants = {
  wide: { height: 72, region: { lat: { min: 2, max: 64 }, lng: { min: -108, max: 104 } } },
  corridor: { height: 70, region: { lat: { min: 4, max: 62 }, lng: { min: -14, max: 98 } } },
};
// Two pins by request: London and Nepal (Nepal's geographic centre).
const places = [
  { id: "london", city: "London", country: "United Kingdom", lat: 51.5072, lng: -0.1276 },
  { id: "nepal", city: "Nepal", country: "Nepal", lat: 28.3949, lng: 84.124 },
];

mkdirSync("public/maps", { recursive: true });
const out = {};
for (const [name, opts] of Object.entries(variants)) {
  const map = new DottedMap({ height: opts.height, grid: "diagonal", region: opts.region });
  const points = map.getPoints();
  const width = Math.max(...points.map((p) => p.x)) + 1;
  const height = Math.max(...points.map((p) => p.y)) + 1;
  // One path of zero-length segments with round caps draws every dot compactly.
  const d = points.map((p) => `M${+p.x.toFixed(2)} ${+p.y.toFixed(2)}h0`).join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}"><path d="${d}" fill="none" stroke="#c9bcff" stroke-opacity=".3" stroke-width=".42" stroke-linecap="round"/></svg>
`;
  writeFileSync(`public/maps/${name}.svg`, svg);
  // Light-surface twin used by the lavender homepage hero (same geometry, darker dots).
  writeFileSync(
    `public/maps/${name}-light.svg`,
    svg.replace('stroke="#c9bcff" stroke-opacity=".3"', 'stroke="#7f9cff" stroke-opacity=".45"'),
  );
  const pins = places.map((p) => {
    const { x, y } = map.getPin({ lat: p.lat, lng: p.lng });
    return { id: p.id, city: p.city, country: p.country, x: +x.toFixed(2), y: +y.toFixed(2) };
  });
  out[name] = { src: `/maps/${name}.svg`, width: +width.toFixed(2), height: +height.toFixed(2), pins };
  console.log(
    name,
    `${width.toFixed(1)}x${height.toFixed(1)}`,
    points.length,
    "dots",
    (svg.length / 1024).toFixed(0),
    "KB",
  );
}
writeFileSync(
  "src/content/hero-map.ts",
  `// Generated by scripts/generate-hero-map.mjs. Do not edit by hand.
export const heroMaps = ${JSON.stringify(out, null, 2)} as const;

export type HeroMapVariant = keyof typeof heroMaps;
`,
);
